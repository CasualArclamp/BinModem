"""Write crates/datapump/src/x2/banks.rs: x2's level banks, as data.

x2's downstream levels for each rate index (1 to 15) and each digital pad
the client reports (none, 3 dB, 6 dB) are not given by any rule anyone has
found. The server firmware builds them at run time. D-Modem
(https://github.com/D-Modem/D-Modem) published the banks the Total Control
Quad x2 firmware (QF060003) builds, read back after running its bank
constructor in an emulator, in `dsp/x2_tables.cpp`. Only those numbers are
taken here, laid out our own way; no code of D-Modem's is used.

    git -C ../D-Modem show <commit>:dsp/x2_tables.cpp > x2_tables.cpp
    python -I tools/x2/gen_banks.py x2_tables.cpp <commit> > crates/datapump/src/x2/banks.rs

The checks below are the ones that make a bank usable at all: MD is 5,
every list sorted with the largest level first, enough digits for B bits,
positions 1 to 5 sharing one list, and rate index 1 with no pad being the
start-up's data levels (levels B) seen on a real I-modem's line.
"""
import re
import sys

LEVELS_B = [0xa5, 0xa8, 0xab, 0xae, 0xb3, 0xb9, 0xbf, 0xcb, 0xdf]


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    commit = sys.argv[2]
    arrays = {}
    for name, body in re.findall(r"static const unsigned char (x2_\w+)\[\d+\] = \{([^}]*)\};", src):
        arrays[name] = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", body)]
    table = src[src.index("x2_rates[X2_MODES][15]"):]
    modes = []
    for block in re.split(r"\n\t\{\n", table)[1:]:
        rates = re.findall(
            r"\{ (\d+), (\d+), \{([^}]*)\},\s*\{([^}]*)\},\s*\{([^}]*)\} \}", block)
        modes.append(rates)
    assert len(modes) == 3, len(modes)
    out = []
    w = out.append
    w("//! x2's level banks: generated by `tools/x2/gen_banks.py`, do not edit.")
    w("//!")
    w("//! The numbers are D-Modem's (https://github.com/D-Modem/D-Modem,")
    w(f"//! `dsp/x2_tables.cpp` at {commit}): the banks U.S. Robotics' Total")
    w("//! Control Quad x2 firmware (QF060003) builds at run time, which D-Modem")
    w("//! read back from the firmware running in an emulator. No rule has been")
    w("//! found that reproduces them, so they are carried as data. Only the")
    w("//! numbers are taken; the layout is ours. For no pad, indices 1, 8, 11,")
    w("//! 12, 13 and 14 are what a U.S. Robotics I-modem was seen to send on the")
    w("//! line; the rest have only been compared with the Quad's.")
    w("//!")
    w("//! Each list is G.711 mu-law octets, positive, the largest level first.")
    w("//! `recv` is what the client receives, `sent` the octet sent so that it")
    w("//! arrives as that level across the pad.")
    w("")
    w("use super::bank::{Bank, List};")
    w("")
    lists = {}
    names = []

    def list_const(recv, sent):
        key = (tuple(recv), tuple(sent))
        if key not in lists:
            name = f"L{len(lists)}"
            lists[key] = name
            names.append((name, recv, sent))
        return lists[key]

    banks = []
    for mode, rates in enumerate(modes):
        assert len(rates) == 15, (mode, len(rates))
        row = []
        for n, (b, md, counts, lv, tx) in enumerate(rates, start=1):
            b, md = int(b), int(md)
            counts = [int(c) for c in counts.split(",")]
            lv = [s.strip() for s in lv.split(",")]
            tx = [s.strip() for s in tx.split(",") if s.strip()]
            assert md == 5, (mode, n, md)
            assert lv[1:] == [lv[1]] * 5, (mode, n, lv)
            if tx:
                assert tx[1:] == [tx[1]] * 5, (mode, n, tx)
            pos = []
            for i in (0, 1):
                recv = arrays[lv[i]]
                sent = arrays[tx[i]] if tx else recv
                assert len(recv) == len(sent) == counts[i], (mode, n, i)
                assert recv == sorted(recv), (mode, n, i)
                assert len(set(recv)) == len(recv), (mode, n, i)
                pos.append(list_const(recv, sent))
            digits = counts[0] * counts[1] ** 5
            assert digits >= 2 ** b, (mode, n, digits, b)
            if n == 1 and mode == 0:
                assert arrays[lv[0]] == LEVELS_B
            row.append((b, pos))
        banks.append(row)
    for name, recv, sent in names:
        w(f"const {name}: List = List {{")
        w(f"    recv: &[{', '.join(f'0x{v:02x}' for v in recv)}],")
        w(f"    sent: &[{', '.join(f'0x{v:02x}' for v in sent)}],")
        w("};")
    w("")
    w("/// `BANKS[pad mode][rate index - 1]`: pad mode 0 none, 1 3 dB, 2 6 dB.")
    w("pub(super) const BANKS: [[Bank; 15]; 3] = [")
    for row in banks:
        w("    [")
        for b, (first, rest) in row:
            w(f"        Bank {{ b: {b}, first: {first}, rest: {rest} }},")
        w("    ],")
    w("];")
    sys.stdout.reconfigure(newline="\n")
    print("\n".join(out))


main()
